-- Complete practice_results migration. Run this entire file in the application database.
-- Single SQL file for all practice schema changes; supports fresh and previously migrated tables.
-- Stop the backend while running, then rebuild/restart it with the current code.
-- Does not modify answer_events. Attribute units use attribute_id + answer_position.
-- Legacy positions are recovered from last_answer_event_id, or default to 1 when unavailable.
-- Duplicate attribute units are merged: keep latest correctness and sum attempt counts.
BEGIN;
CREATE TABLE IF NOT EXISTS public.practice_results (
    practice_result_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id               BIGINT       NOT NULL,
    question_id           BIGINT       NOT NULL,
    -- NULL for MCQ (the question itself is the unit).
    question_attribute_id BIGINT,

    -- Denormalised from the question so the performance queries don't have to
    -- walk questions -> topic -> chapter -> subject -> course. The service
    -- validates them against the question before writing.
    course_id             BIGINT       NOT NULL,
    subject_id            BIGINT       NOT NULL,
    chapter_id            BIGINT       NOT NULL,
    topic_id              BIGINT       NOT NULL,

    question_type         VARCHAR(30)  NOT NULL,
    is_correct            BOOLEAN      NOT NULL,
    -- Lifetime attempt count for this unit. Reset does not clear it.
    -- 1 on the first attempt, +1 on every repeat.
    attempt_number        INTEGER      NOT NULL DEFAULT 1,

    answered_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Derived data: it goes with the user / question / attribute it describes.
    CONSTRAINT fk_practice_results_user
        FOREIGN KEY (user_id) REFERENCES public.users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_practice_results_question
        FOREIGN KEY (question_id) REFERENCES public.questions (question_id) ON DELETE CASCADE,
    CONSTRAINT fk_practice_results_question_attribute
        FOREIGN KEY (question_attribute_id)
        REFERENCES public.question_attributes (question_attribute_id) ON DELETE CASCADE,

    CONSTRAINT fk_practice_results_course
        FOREIGN KEY (course_id) REFERENCES public.courses (course_id),
    CONSTRAINT fk_practice_results_subject
        FOREIGN KEY (subject_id) REFERENCES public.subject (subject_id),
    CONSTRAINT fk_practice_results_chapter
        FOREIGN KEY (chapter_id) REFERENCES public.chapters (chapter_id),
    CONSTRAINT fk_practice_results_topic
        FOREIGN KEY (topic_id) REFERENCES public.topic (topic_id),

    CONSTRAINT chk_practice_results_type
        CHECK (question_type IN ('ATTRIBUTE', 'MCQ')),
    -- An MCQ row never has an attribute; an ATTRIBUTE row always does.
    CONSTRAINT chk_practice_results_unit
        CHECK ((question_type = 'MCQ') = (question_attribute_id IS NULL))
);


ALTER TABLE public.practice_results ADD COLUMN IF NOT EXISTS answer_position INTEGER;
-- Re-running schema/data repairs must not create a practice day.
DROP TRIGGER IF EXISTS practice_results_track_day ON public.practice_results;
ALTER TABLE public.practice_results ADD COLUMN IF NOT EXISTS last_answer_event_id BIGINT
    REFERENCES public.answer_events(answer_event_id);
ALTER TABLE public.practice_results DROP CONSTRAINT IF EXISTS chk_practice_results_type;
ALTER TABLE public.practice_results DROP CONSTRAINT IF EXISTS chk_practice_results_unit;
DROP INDEX IF EXISTS public.uq_practice_results_question;
ALTER TABLE public.practice_results ADD CONSTRAINT chk_practice_results_type
    CHECK (question_type IN ('ATTRIBUTE', 'MCQ', 'FILL_BLANK', 'MATCHING'));

ALTER TABLE public.practice_results ADD COLUMN IF NOT EXISTS attribute_id BIGINT
    REFERENCES public.table_attributes(attribute_id);
DROP INDEX IF EXISTS public.uq_practice_results_attribute;
DROP INDEX IF EXISTS public.uq_practice_results_unit;
ALTER TABLE public.practice_results DROP COLUMN IF EXISTS unit_key;
UPDATE public.practice_results pr SET attribute_id = qa.attribute_id
FROM public.question_attributes qa
WHERE qa.question_attribute_id = pr.question_attribute_id AND pr.question_type = 'ATTRIBUTE';
UPDATE public.practice_results pr SET answer_position = COALESCE(
    (SELECT ae.answer_position FROM public.answer_events ae
     WHERE ae.answer_event_id = pr.last_answer_event_id), 1)
WHERE pr.question_type = 'ATTRIBUTE' AND pr.answer_position IS NULL;
WITH ranked AS (
    SELECT practice_result_id,
        ROW_NUMBER() OVER (PARTITION BY user_id, question_id, attribute_id, answer_position
            ORDER BY answered_at DESC, practice_result_id DESC) AS rn,
        SUM(attempt_number) OVER (PARTITION BY user_id, question_id, attribute_id, answer_position) AS attempts
    FROM public.practice_results WHERE question_type = 'ATTRIBUTE'
)
UPDATE public.practice_results pr SET attempt_number = ranked.attempts
FROM ranked WHERE ranked.practice_result_id = pr.practice_result_id AND ranked.rn = 1;
WITH ranked AS (
    SELECT practice_result_id,
        ROW_NUMBER() OVER (PARTITION BY user_id, question_id, attribute_id, answer_position
            ORDER BY answered_at DESC, practice_result_id DESC) AS rn
    FROM public.practice_results WHERE question_type = 'ATTRIBUTE'
)
DELETE FROM public.practice_results pr USING ranked
WHERE ranked.practice_result_id = pr.practice_result_id AND ranked.rn > 1;
ALTER TABLE public.practice_results ADD CONSTRAINT chk_practice_results_unit CHECK (
    (question_type = 'ATTRIBUTE' AND attribute_id IS NOT NULL
        AND answer_position IS NOT NULL AND answer_position BETWEEN 1 AND 4)
    OR (question_type = 'MCQ' AND attribute_id IS NULL AND question_attribute_id IS NULL AND answer_position IS NULL)
    OR (question_type IN ('FILL_BLANK', 'MATCHING') AND attribute_id IS NULL AND question_attribute_id IS NULL
        AND answer_position IS NOT NULL AND answer_position > 0)
);
ALTER TABLE public.practice_results ADD COLUMN unit_key TEXT GENERATED ALWAYS AS (
    CASE WHEN attribute_id IS NOT NULL THEN 'ATTRIBUTE:' || attribute_id::text || ':' || answer_position::text
         WHEN answer_position IS NOT NULL THEN question_type || ':' || answer_position::text
         ELSE 'MCQ' END
) STORED;
CREATE UNIQUE INDEX uq_practice_results_attribute
    ON public.practice_results(user_id, question_id, attribute_id, answer_position)
    WHERE attribute_id IS NOT NULL;
CREATE UNIQUE INDEX uq_practice_results_unit ON public.practice_results(user_id, question_id, unit_key);


CREATE UNIQUE INDEX uq_practice_results_question
    ON public.practice_results(user_id, question_id)
    WHERE question_attribute_id IS NULL AND answer_position IS NULL;
-- Performance queries group one level's rows by that level's id and join to a
-- set of students. INCLUDE (is_correct) lets them be answered from the index.
CREATE INDEX IF NOT EXISTS idx_practice_results_course
    ON public.practice_results (course_id, user_id) INCLUDE (is_correct);
CREATE INDEX IF NOT EXISTS idx_practice_results_subject
    ON public.practice_results (subject_id, user_id) INCLUDE (is_correct);
CREATE INDEX IF NOT EXISTS idx_practice_results_chapter
    ON public.practice_results (chapter_id, user_id) INCLUDE (is_correct);
CREATE INDEX IF NOT EXISTS idx_practice_results_topic
    ON public.practice_results (topic_id, user_id) INCLUDE (is_correct);

-- Foreign-key lookups (ON DELETE CASCADE and joins by question / attribute).
CREATE INDEX IF NOT EXISTS idx_practice_results_question
    ON public.practice_results (question_id);
CREATE INDEX IF NOT EXISTS idx_practice_results_question_attribute
    ON public.practice_results (question_attribute_id)
    WHERE question_attribute_id IS NOT NULL;

-- Persistent distinct questions per India calendar day. Reset and later retries
-- do not erase earlier days. All practice write paths (including MCQs) use this
-- trigger; answer_events is unchanged. Existing rows recover only their latest
-- known day, not a fabricated historical streak.
CREATE TABLE IF NOT EXISTS public.practice_daily_questions (
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    -- Keep the historical question id even if that question is later removed.
    question_id BIGINT NOT NULL,
    practice_date DATE NOT NULL,
    PRIMARY KEY (user_id, practice_date, question_id)
);
INSERT INTO public.practice_daily_questions(user_id, question_id, practice_date)
SELECT DISTINCT user_id, question_id, answered_at::date FROM public.practice_results
WHERE answered_at IS NOT NULL
ON CONFLICT DO NOTHING;

CREATE OR REPLACE FUNCTION public.track_practice_day() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.answered_at IS NOT DISTINCT FROM OLD.answered_at
        AND NEW.attempt_number IS NOT DISTINCT FROM OLD.attempt_number THEN
        RETURN NEW;
    END IF;
    INSERT INTO public.practice_daily_questions(user_id, question_id, practice_date)
    VALUES (NEW.user_id, NEW.question_id, (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Calcutta')::date)
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS practice_results_track_day ON public.practice_results;
CREATE TRIGGER practice_results_track_day
AFTER INSERT OR UPDATE OF answered_at, attempt_number ON public.practice_results
FOR EACH ROW EXECUTE FUNCTION public.track_practice_day();

COMMIT;
