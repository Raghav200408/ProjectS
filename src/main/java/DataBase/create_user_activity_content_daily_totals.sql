-- Content-level active study-time buckets. Run after create_user_activity_sessions.sql.
-- Existing session totals remain unchanged; this table is populated from deployment onward.

ALTER TABLE public.user_activity_sessions
    ADD COLUMN IF NOT EXISTS current_chapter_id BIGINT,
    ADD COLUMN IF NOT EXISTS current_chapter_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS current_topic_id BIGINT,
    ADD COLUMN IF NOT EXISTS current_topic_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS current_question_id BIGINT,
    ADD COLUMN IF NOT EXISTS current_question_name VARCHAR(500);

CREATE TABLE IF NOT EXISTS public.user_activity_content_daily_totals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    activity_date DATE NOT NULL,
    content_level VARCHAR(16) NOT NULL,
    content_id BIGINT NOT NULL,
    content_name VARCHAR(500) NOT NULL,
    active_seconds BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_user_activity_content_daily_user
        FOREIGN KEY (user_id) REFERENCES public.users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_user_activity_content_level
        CHECK (content_level IN ('CHAPTER', 'TOPIC', 'QUESTION')),
    CONSTRAINT chk_user_activity_content_seconds CHECK (active_seconds >= 0),
    CONSTRAINT uq_user_activity_content_daily
        UNIQUE (user_id, activity_date, content_level, content_id)
);

CREATE INDEX IF NOT EXISTS idx_user_activity_content_daily_lookup
    ON public.user_activity_content_daily_totals
        (user_id, content_level, activity_date);
