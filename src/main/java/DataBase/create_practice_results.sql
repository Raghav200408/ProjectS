-- ============================================================
-- practice_results: the CURRENT practice state of one unit for one student.
--
-- answer_events stays the historical record (every attempt, kept forever).
-- This table keeps exactly one row per (student, unit) and is updated in
-- place when the student attempts that unit again, so the performance
-- screens can aggregate it without counting repeated attempts twice.
--
-- What "one unit" means:
--   * Journal / Dropdown / Drag-and-drop -> one question_attributes row
--       (question_attribute_id set, question_type = 'ATTRIBUTE')
--   * MCQ (single or multiple)           -> the whole question
--       (question_attribute_id NULL,    question_type = 'MCQ')
-- Matching and Fill-in-the-blank are NOT stored here yet: their events can't
-- identify a single pair / blank (see the design notes), so no unit column is
-- invented for them.
--
-- There is no totalAttributes column on purpose - the total number of units is
-- read from question_attributes at query time. Storing it on every row would
-- multiply it by the number of attempted attributes.
--
-- Run once against the Hintmatrix DB before deploying the matching backend
-- build. There is no ddl-auto / Flyway in this project. Safe to re-run.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.practice_results (
    practice_result_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id               BIGINT       NOT NULL,
    question_id           BIGINT       NOT NULL,
    -- NULL for MCQ (the question itself is the unit).
    question_attribute_id BIGINT,

    -- Denormalised from the question so the performance queries don't have to
    -- walk questions -> topic -> chapter -> subject -> course. The service
    -- validates them against the question before writing.
    course_id             BIGINT       NOT NULL,
    subject_id            BIGINT       NOT NULL,
    chapter_id            BIGINT       NOT NULL,
    topic_id              BIGINT       NOT NULL,

    question_type         VARCHAR(30)  NOT NULL,
    is_correct            BOOLEAN      NOT NULL,
    -- How many times the student has attempted this unit since it was last
    -- reset. 1 on the first attempt, +1 on every repeat.
    attempt_number        INTEGER      NOT NULL DEFAULT 1,

    answered_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Derived data: it goes with the user / question / attribute it describes.
    CONSTRAINT fk_practice_results_user
        FOREIGN KEY (user_id) REFERENCES public.users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_practice_results_question
        FOREIGN KEY (question_id) REFERENCES public.questions (question_id) ON DELETE CASCADE,
    CONSTRAINT fk_practice_results_question_attribute
        FOREIGN KEY (question_attribute_id)
        REFERENCES public.question_attributes (question_attribute_id) ON DELETE CASCADE,

    CONSTRAINT fk_practice_results_course
        FOREIGN KEY (course_id) REFERENCES public.courses (course_id),
    CONSTRAINT fk_practice_results_subject
        FOREIGN KEY (subject_id) REFERENCES public.subject (subject_id),
    CONSTRAINT fk_practice_results_chapter
        FOREIGN KEY (chapter_id) REFERENCES public.chapters (chapter_id),
    CONSTRAINT fk_practice_results_topic
        FOREIGN KEY (topic_id) REFERENCES public.topic (topic_id),

    CONSTRAINT chk_practice_results_type
        CHECK (question_type IN ('ATTRIBUTE', 'MCQ')),
    -- An MCQ row never has an attribute; an ATTRIBUTE row always does.
    CONSTRAINT chk_practice_results_unit
        CHECK ((question_type = 'MCQ') = (question_attribute_id IS NULL))
);

-- One current row per unit. A plain UNIQUE (user_id, question_id,
-- question_attribute_id) would NOT stop duplicate MCQ rows because PostgreSQL
-- treats NULLs as distinct, so the two shapes get their own partial index.
-- These are also the ON CONFLICT targets of the upsert.
CREATE UNIQUE INDEX IF NOT EXISTS uq_practice_results_attribute
    ON public.practice_results (user_id, question_id, question_attribute_id)
    WHERE question_attribute_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_practice_results_question
    ON public.practice_results (user_id, question_id)
    WHERE question_attribute_id IS NULL;

-- Performance queries group one level's rows by that level's id and join to a
-- set of students. INCLUDE (is_correct) lets them be answered from the index.
CREATE INDEX IF NOT EXISTS idx_practice_results_course
    ON public.practice_results (course_id, user_id) INCLUDE (is_correct);
CREATE INDEX IF NOT EXISTS idx_practice_results_subject
    ON public.practice_results (subject_id, user_id) INCLUDE (is_correct);
CREATE INDEX IF NOT EXISTS idx_practice_results_chapter
    ON public.practice_results (chapter_id, user_id) INCLUDE (is_correct);
CREATE INDEX IF NOT EXISTS idx_practice_results_topic
    ON public.practice_results (topic_id, user_id) INCLUDE (is_correct);

-- Foreign-key lookups (ON DELETE CASCADE and joins by question / attribute).
CREATE INDEX IF NOT EXISTS idx_practice_results_question
    ON public.practice_results (question_id);
CREATE INDEX IF NOT EXISTS idx_practice_results_question_attribute
    ON public.practice_results (question_attribute_id)
    WHERE question_attribute_id IS NOT NULL;
